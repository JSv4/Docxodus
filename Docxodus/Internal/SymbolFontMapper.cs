using System.Collections.Generic;
using System.Text;

namespace Docxodus.Internal;

/// <summary>
/// Maps text set in a symbol font (Symbol, Wingdings, Wingdings 2, Wingdings 3, Webdings) to Unicode.
/// Word stores such text as the font's own byte, either bare (U+0020–U+00FF) or moved into the
/// private-use area (U+F020–U+F0FF), so it renders as a blank box wherever the font is not installed.
/// The real Unicode character renders everywhere. A byte with no faithful Unicode equivalent is
/// unmapped, and unmapped characters are returned unchanged so nothing is lost.
/// </summary>
internal static class SymbolFontMapper
{
    // Code points for bytes 0x20–0xFF, sixteen to a row; 0 means no faithful Unicode equivalent.
    //
    // Symbol: Unicode's Adobe Symbol mapping (https://unicode.org/Public/MAPPINGS/VENDORS/ADOBE/symbol.txt,
    // table version 1.0). Its 29 Corporate Use Subarea targets (U+F6D9–U+F8FE: bracket and integral pieces,
    // arrow extenders, the radical extender and the serif/sans-serif (R) (C) TM) are private use too, so they
    // are 0 here; the (R) (C) TM bytes are restored by Overrides. Where it lists two code points for one
    // byte, the first in Adobe glyph-list order is kept: SPACE, GREEK CAPITAL LETTER DELTA and OMEGA,
    // GREEK SMALL LETTER MU and FRACTION SLASH.
    //
    // Wingdings, Wingdings 2, Wingdings 3 and Webdings: the normative source references of WG2 N4384,
    // "Status of encoding of Wingdings and Webdings Symbols" (https://www.unicode.org/L2/L2012/12368-n4384.pdf,
    // section 7), which encoded them in Unicode 7.0. It leaves unmapped only Wingdings' Windows logo (0xFF)
    // and the bytes the fonts leave empty. Every code point is assigned in Unicode 16.0.
    //
    // The tables themselves are at the end of this file.
    private static int[]? TableFor(string font) => font switch
    {
        "symbol" => Symbol, "wingdings" => Wingdings, "wingdings 2" => Wingdings2,
        "wingdings 3" => Wingdings3, "webdings" => Webdings, _ => null,
    };

    // Deliberate departures from the tables above, each the same symbol at an older code point that far
    // more fonts carry. The form-control glyphs a check box is drawn with map to the ballot boxes and
    // marks (U+2610–U+2612, U+2713, U+2717), which Unicode 7.0's U+1F5F4–U+1F5F9 and U+1F78E–U+1F78F
    // repeat in styled forms most fonts lack, so a checked box would again look like an empty one.
    // Wingdings 0x6E and 0xD8 keep the list-bullet glyphs this mapper produced before it had full tables.
    private static readonly Dictionary<(string Font, int Code), int> Overrides = new()
    {
        { ("symbol", 0xD2), 0xAE }, { ("symbol", 0xD3), 0xA9 }, { ("symbol", 0xD4), 0x2122 }, // serif (R) (C) TM
        { ("symbol", 0xE2), 0xAE }, { ("symbol", 0xE3), 0xA9 }, { ("symbol", 0xE4), 0x2122 }, // sans-serif
        { ("wingdings", 0x6E), 0x25A0 }, // ■ black square (Unicode: U+25FC)
        { ("wingdings", 0x6F), 0x2610 }, // ☐ ballot box (U+1F78F medium white square)
        { ("wingdings", 0xA8), 0x2610 }, // ☐ ballot box (U+1F78E light white square)
        { ("wingdings", 0xD8), 0x27A2 }, // ➢ three-D top-lighted rightwards arrowhead (U+2B9A)
        { ("wingdings", 0xFB), 0x2717 }, // ✗ ballot X (U+1F5F6 ballot bold script X)
        { ("wingdings", 0xFD), 0x2612 }, // ☒ ballot box with X (U+1F5F7, bold script X)
        { ("wingdings", 0xFE), 0x2611 }, // ☑ ballot box with check (U+1F5F9, bold check)
        { ("wingdings 2", 0x4F), 0x2717 }, // ✗ ballot X (U+1F5F4 ballot script X)
        { ("wingdings 2", 0x50), 0x2713 }, // ✓ check mark (U+1F5F8 light check mark)
        { ("wingdings 2", 0x51), 0x2612 }, // ☒ ballot box with X (U+1F5F5, script X)
    };

    // Each symbol font's ascent in ems: its hhea ascender, equal to its OS/2 winAscent, over 2048 units
    // per em (Windows 11 copies; none has a line gap). Word lifts a line to the ascent of the fonts on
    // it, so a mapped glyph keeps the ascent of the font it replaces (#1567): a 12pt Symbol bullet over
    // 12pt Arial makes a 14.61pt line, not Arial's 13.80pt.
    private static readonly Dictionary<string, decimal> Ascents = new()
    {
        { "symbol", 2059m / 2048m }, { "wingdings", 1841m / 2048m }, { "wingdings 2", 1727m / 2048m },
        { "wingdings 3", 1900m / 2048m }, { "webdings", 1638m / 2048m },
    };

    private static readonly string[] Families = { "symbol", "wingdings", "wingdings 2", "wingdings 3", "webdings" };

    /// <summary>
    /// The symbol font a CSS font-family value names first, lowercased, or "" for any other family.
    /// Every run with a font asks, so this allocates nothing.
    /// </summary>
    private static string PrimaryFamily(string fontFamily)
    {
        var first = fontFamily.AsSpan();
        var comma = first.IndexOf(',');
        if (comma >= 0) first = first[..comma];
        first = first.Trim().Trim("'\"");
        foreach (var family in Families)
            if (first.Equals(family, System.StringComparison.OrdinalIgnoreCase)) return family;
        return "";
    }

    /// <summary>
    /// The families after the primary one in a CSS font-family value, or null when there are none:
    /// what a mapped glyph renders in once the symbol face is dropped.
    /// </summary>
    public static string? FallbackFamilies(string fontFamily)
    {
        var comma = fontFamily.IndexOf(',');
        var rest = comma < 0 ? "" : fontFamily[(comma + 1)..].Trim();
        return rest.Length == 0 ? null : rest;
    }

    /// <summary>True if <paramref name="fontFamily"/>'s primary family is a known symbol font.</summary>
    public static bool IsSymbolFont(string? fontFamily) =>
        fontFamily != null && Ascents.ContainsKey(PrimaryFamily(fontFamily));

    /// <summary>The ascent, in ems, of the symbol font <paramref name="fontFamily"/> names first.</summary>
    public static decimal Ascent(string fontFamily) => Ascents[PrimaryFamily(fontFamily)];

    /// <summary>
    /// The Unicode text for <paramref name="ch"/> set in <paramref name="fontFamily"/>, or null when it
    /// has no faithful equivalent (or the font is not a symbol font). A code point that browsers draw as
    /// a colour emoji by default is followed by U+FE0E, which asks for its monochrome text form, as
    /// the font draws it.
    /// </summary>
    public static string? Map(char ch, string fontFamily)
    {
        var code = ch is >= '\uF020' and <= '\uF0FF' ? ch - 0xF000 : ch is >= ' ' and <= '\u00FF' ? ch : -1;
        var font = PrimaryFamily(fontFamily);
        if (code < 0 || TableFor(font) is not { } table) return null;
        var mapped = Overrides.TryGetValue((font, code), out var chosen) ? chosen : table[code - 0x20];
        if (mapped == 0) return null;
        var text = char.ConvertFromUtf32(mapped);
        return EmojiPresentation.Contains(mapped) ? text + "\uFE0E" : text;
    }

    /// <summary>
    /// Map each character of <paramref name="text"/> from <paramref name="fontFamily"/> to Unicode.
    /// Unmapped characters are left unchanged.
    /// </summary>
    public static string MapText(string text, string fontFamily)
    {
        var sb = new StringBuilder(text.Length);
        foreach (var ch in text)
            sb.Append(Map(ch, fontFamily) ?? ch.ToString());
        return sb.ToString();
    }

